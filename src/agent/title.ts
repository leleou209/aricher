// 会话标题：让模型读完开场白，替这场对话起个名字。
//
// 以前是把第一句提问截前 18 个字。问题在于开场白往往什么信息都没有 ——
// 「我今天想问你一个事」「在吗」「帮我看个东西」，截出来一排半句话，
// 侧栏看着不像一串话题，像一串被掐断的句子。

/**
 * 起标题的提示词。
 *
 * 要求写得这么碎，是因为模型的默认手笔就是「关于 XX 的讨论」这类空壳 ——
 * 听着像会议纪要，摆在侧栏里等于没写。宁可它起得朴素一点，也别起一个套话。
 */
export const TITLE_SYSTEM =
  "你叫 ericher，在给这场对话起个名字，就像人过后回忆这件事时会怎么称呼它。" +
  "只输出名字本身：不要引号、不要书名号、不要句号、不要「标题：」这样的前缀。" +
  "6 到 14 个字，说清这件事是什么。别用「对话」「讨论」「交流」「关于」「问题」这类空词。";

/**
 * 按「这场是谁在说话」把提示词补完整。
 *
 * 为什么要分开：侧栏里主人的会话和来客的会话并排摆着，起名用的是同一个模型、
 * 同一套要求。要是不说清说话的是谁，模型就会顺手把来客那几场也写成
 * 「管理员在问…」—— 名字是给以后翻侧栏的人看的，认错了人就等于记错了账。
 * 主人那间说「是管理员本人」，来客那间要额外挡一句「别用管理员称呼说话的人」。
 */
export function titleSystem(guest: boolean): string {
  return (
    TITLE_SYSTEM +
    (guest
      ? "和你说话的是来客 —— 标题里不要用「管理员」或任何人名来称呼说话的人。"
      : "和你说话的是管理员本人。")
  );
}

/** 起标题时给模型看的东西。只给开头一小段：标题要的是话题，不是全部细节。 */
export function titlePrompt(
  opening: string,
  answer: string,
  guest = false,
): string {
  // 被打断的那一轮可能一个字都没说出来 —— 那就只凭开场白起，
  // 空着「我回：」比编一句更诚实
  const mine = answer.trim();
  return `${guest ? "来客" : "用户"}说：${opening}${mine ? `\n\n我回：${mine}` : ""}\n\n给这段对话起个名字。`;
}

/**
 * 成对的包装：模型最爱把名字整个套进一对引号或书名号里。
 */
const WRAPPERS: Array<[string, string]> = [
  ["「", "」"],
  ["『", "』"],
  ["【", "】"],
  ["《", "》"],
  ["“", "”"],
  ["‘", "’"],
  ['"', '"'],
  ["'", "'"],
  ["（", "）"],
  ["(", ")"],
];

/**
 * 脱掉外面那一层包装，只脱一层。
 *
 * 为什么必须「两边都在」才脱：像「改简历（第一版）」这种，右边那个括号
 * 是名字的一部分，见着右括号就砍尾巴，会把好好的名字啃掉半截。
 */
function unwrap(s: string): string {
  for (const [open, close] of WRAPPERS) {
    if (s.length > 2 && s.startsWith(open) && s.endsWith(close))
      return s.slice(1, -1).trim();
  }
  return s;
}

/**
 * 把模型交回来的那行字收拾干净。
 *
 * 收拾的不是「万一」：提示词里明写了不要引号、不要前缀，它照样会时不时加回来。
 * 而标题会直接摆进侧栏的按钮上，多一个引号、多一句「标题：」，一眼就看得出是机器写的。
 */
export function tidyTitle(raw: string): string {
  const first =
    raw
      .split("\n")
      .map((s) => s.trim())
      .find((s) => s) || "";

  const named = first
    // 「标题：」「名字：」这类前缀
    .replace(/^(标题|名字|会话名|名称)\s*[:：]\s*/, "")
    .trim();

  return (
    unwrap(named)
      // 结尾的句号感叹号：标题不是句子
      .replace(/[。！？.!?、；;，,]+$/, "")
      .replace(/\s+/g, " ")
      .trim()
      .slice(0, 20)
  );
}
